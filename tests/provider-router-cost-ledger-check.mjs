assert.ok(exportPackSource.includes('provider/provider-route-plan.json'),'export pack must include route plan');
assert.ok(exportPackSource.includes('provider/provider-cost-report.json'),'export pack must include cost report');
assert.equal(schema.properties.workflow_version.const,VERSION);
for(const key of ['provider_route_plan','provider_route_report','provider_cost_report','provider_router_safety_report']) assert.ok(schema.required.includes(key),`schema must require ${key}`);
